def _import_canonical_or_legacy(canonical: str, legacy: str) -> Any:
    try:
        return import_module(canonical)
    except ModuleNotFoundError as exc:
        # Fall back only when the canonical module itself (or a parent package)
        # is absent. A missing dependency *inside* it is a real error.
        if exc.name is None or not (canonical == exc.name or canonical.startswith(exc.name + ".")):
            raise
        return import_module(legacy)


def __getattr__(name: str) -> Any:
    try:
        canonical, legacy = _LOCATIONS[name]
    except KeyError:
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}") from None
    value = getattr(_import_canonical_or_legacy(canonical, legacy), name)
    globals()[name] = value
    return value


def __dir__() -> list[str]:
    return sorted(set(globals()) | set(_LOCATIONS))
